export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  const { user } = useAuth();

  useEffect(() => {
    AsyncStorage.getItem(LANG_KEY)
      .then((v) => { if (v && ALL_LANGS.has(v)) setLangState(v as Lang); })
      .catch(() => { /* keep default language */ });
  }, []);

  // Inherit Flexa Market preferred language from the signed-in profile (server source of truth).
  useEffect(() => {
    const preferred = (user as { preferredLanguage?: string | null } | null)?.preferredLanguage;
    if (!preferred || !ALL_LANGS.has(preferred)) return;
    setLangState((prev) => {
      if (prev === preferred) return prev;
      AsyncStorage.setItem(LANG_KEY, preferred).catch(() => {});
      return preferred as Lang;
    });
  }, [user]);

  const setLang = useCallback(async (l: Lang) => {
    setLangState(l);
    AsyncStorage.setItem(LANG_KEY, l).catch(() => {});
  }, []);

  const t = useCallback(
    (key: string): string => {
      const english = T.en[key];
      if (english && (/retry|tryAgain/i.test(key) || /\btry\b[^.!?\n]*\bagain\b|\bretry\b/i.test(english))) return english;
      return T[lang]?.[key] ?? english ?? T.ht[key] ?? key;
    },
    [lang]
  );

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
