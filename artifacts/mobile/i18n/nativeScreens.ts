export function friendlyApiError(raw: string | undefined, t: (k: string) => string): string {
  const msg = (raw || "").toLowerCase();
  if (!msg) return t("common_loadFailed");
  if (msg.includes("invalid token") || msg.includes("unauthorized") || msg.includes("401")) {
    return t("common_sessionExpired");
  }
  return raw || t("common_loadFailed");
}

export function tr(
  t: (k: string) => string,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let s = t(key);
  if (!vars) return s;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replace(new RegExp(`\\{\\{${k}\\}\\}`, "g"), String(v));
  }
  return s;
}
